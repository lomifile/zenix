def ramp(dark: str, end: str) -> list[str]:
    return [blend(dark, end, 0.35), blend(dark, end, 0.65), end]


def catppuccin(flavour: str) -> dict:
    return {
        "name": f"catppuccin-{flavour}",
        "label": LABELS[flavour],
        "palette": FLAVOURS[flavour],
        "light": flavour == "latte",
        "gtk": f"catppuccin-{flavour}-{ACCENT}-standard+default",
        "folders": f"cat-{flavour}-{ACCENT}",
        "apps_comment": (
            "Theme names, not colours. The GTK theme comes from "
            f"catppuccin-gtk-theme-{flavour}, which installs every accent; "
            "the folder colour comes from papirus-folders-catppuccin-git."
        ),
    }


