"""Author the generated theme files: Catppuccin, Tokyo Night and Nord.

A dev-time tool, not part of `zenix theme set`: it turns upstream palettes into
zenix's own role schema once, and the result is committed. Re-run it only to
change a mapping, then review the diff.

    python3 themes/make-themes.py            # write every generated theme
    python3 themes/make-themes.py --check    # fail if any is stale

Every palette is expressed in Catppuccin's role names (base, surface0,
overlay1, blue, ...), so one mapping paints every surface of every theme.
"""

