def tokyonight(variant: str) -> dict:
    return {
        "name": f"tokyonight-{variant}",
        "label": "Tokyo Night" if variant == "night" else f"Tokyo Night {variant.capitalize()}",
        "palette": TOKYONIGHT[variant],
        "gtk": "Tokyonight-Dark",
        "folders": "blue",
        "apps_comment": (
            "Theme names, not colours. The GTK theme comes from "
            "tokyonight-gtk-theme-git, whose default build is the night "
            "variant; storm shares it. Folders use papirus' stock blue."
        ),
    }


def nord() -> dict:
    return {
        "name": "nord",
        "label": "Nord",
        "palette": NORD,
        "gtk": "Nordic",
        "folders": "nordic",
        "apps_comment": (
            "Theme names, not colours. The GTK theme comes from nordic-theme; "
            "folders use papirus' stock nordic colour."
        ),
    }


def specs() -> list[dict]:
    return (
        [catppuccin(f) for f in FLAVOURS]
        + [tokyonight(v) for v in TOKYONIGHT]
        + [nord()]
    )


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for spec in specs():
        path = HERE / f"{spec['name']}.json"
        text = json.dumps(build(spec), indent=2) + "\n"
        if check:
            if not path.is_file() or path.read_text() != text:
                stale.append(path.name)
            continue
        path.write_text(text)
        print(f"wrote themes/{path.name}")
    if check:
        for name in stale:
            print(f"stale: {name}")
        return 1 if stale else 0
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
