"""Palettes, and the per-surface config files generated from them.

A theme is one JSON file in `themes/`. Every surface in the setup is then
written from it, by one of four strategies depending on how much the file
carries besides colour:

  fully generated   the file is nothing but palette, so it is written outright
  marked block      the file has layout or logic worth keeping, so only the
                    region between two marker comments is replaced
  structural block  the same, for a file a third party rewrites and whose
                    comments therefore cannot be relied on (lazygit)
  selector          one line names a theme the app loads for itself

Every `render_*` is a pure function of the theme and returns file text, so the
whole generator is testable without touching a filesystem. The `rewrite_*`
functions additionally take the file's current text, because they preserve it.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from zenix.console import die

THEMES_DIRNAME = "themes"

# Marker pairs, by the comment syntax of the file they go in.
MARKERS = {
    "hash": ("# >>> zenix theme <<<", "# >>> end zenix theme <<<"),
    "lua": ("-- >>> zenix theme <<<", "-- >>> end zenix theme <<<"),
    "css": ("/* >>> zenix theme <<< */", "/* >>> end zenix theme <<< */"),
}

GENERATED_BY = "Generated by `zenix theme set {name}` -- edit themes/{name}.json, not this."


# -- loading -----------------------------------------------------------------


class Theme:
    """One theme file, with each section reachable as an attribute.

    Sections are plain dicts straight from the JSON. A missing key is a hard
    error rather than a default: a theme that cannot paint every surface would
    otherwise leave part of the desktop on the previous palette.
    """

    SECTIONS = (
        "meta", "editor", "terminal", "desktop", "washes", "css",
        "hypr", "hyprlock", "sddm", "waybar", "btop_ramps", "grub", "apps",
    )

    def __init__(self, name: str, data: dict) -> None:
        self.name = name
        self.data = data
        for section in self.SECTIONS:
            if section not in data:
                die(f"themes/{name}.json has no [{section}] section")
            setattr(self, section, data[section])

    def __getitem__(self, path: str):
        """`theme["editor.bg"]`, with a message that names the theme on a miss."""
        section, _, key = path.partition(".")
        try:
            return getattr(self, section)[key]
        except (AttributeError, KeyError):
            die(f"themes/{self.name}.json is missing {path}")

    @property
    def label(self) -> str:
        return self.meta.get("label", self.name)

    @property
    def is_dark(self) -> bool:
        return self.meta.get("background", "dark") == "dark"


def themes_dir(repo) -> Path:
    return repo.root / THEMES_DIRNAME


def names(repo) -> list[str]:
    d = themes_dir(repo)
    if not d.is_dir():
        return []
    return sorted(p.stem for p in d.glob("*.json"))


def load(repo, name: str) -> Theme:
    path = themes_dir(repo) / f"{name}.json"
    if not path.is_file():
        available = ", ".join(names(repo)) or "none found"
        die(f"no such theme: {name} (available: {available})")
    try:
        data = json.loads(path.read_text())
    except json.JSONDecodeError as exc:
        die(f"themes/{name}.json is not valid JSON: {exc}")
    return Theme(name, data)


# -- colour helpers ----------------------------------------------------------


def _channels(hex_colour: str) -> tuple[int, int, int]:
    h = hex_colour.lstrip("#")
    if len(h) == 8:  # #AARRGGBB -- drop the alpha
        h = h[2:]
    if len(h) != 6:
        die(f"not a 6-digit hex colour: {hex_colour}")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def blend(base: str, over: str, t: float) -> str:
    """`over` laid on `base` at opacity `t`, flattened to an opaque hex.

    How the upstream Catppuccin ports build their diff and search backgrounds:
    a saturated accent at ~15% over the editor background, which stays legible
    under text where the accent itself would not.
    """
    b, o = _channels(base), _channels(over)
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(b, o))


def ramp(dark: str, end: str, stops: int = 3) -> list[str]:
    """A gradient from near-`dark` up to `end`, for btop's meters."""
    lo = 1.0 / (stops + 1)
    out = [blend(dark, end, lo + (1.0 - lo) * i / (stops - 1)) for i in range(stops - 1)]
    return out + [end]


def packed(hex_colour: str, alpha: str = "ff") -> str:
    """`rgba(rrggbbaa)` -- hyprland's own spelling."""
    return f"rgba({hex_colour.lstrip('#')}{alpha})"


# -- block replacement -------------------------------------------------------


def replace_block(text: str, syntax: str, body: str, *, what: str) -> str:
    """Swap the lines between the markers for `body`, keeping the markers.

    The markers must already be in the file. Inserting them is a one-off edit
    done by hand when the surface is first brought under the generator, so that
    the person doing it chooses where the block sits rather than the generator
    guessing.
    """
    opener, closer = MARKERS[syntax]
    pat = re.compile(
        rf"^([ \t]*){re.escape(opener)}[^\n]*\n.*?^[ \t]*{re.escape(closer)}[^\n]*$",
        re.S | re.M,
    )
    m = pat.search(text)
    if not m:
        die(
            f"{what} has no `{opener}` / `{closer}` block; "
            "the CLI and the config are out of sync"
        )
    indent = m.group(1)
    lines = [f"{indent}{opener}"]
    lines += [f"{indent}{line}".rstrip() for line in body.splitlines()]
    lines.append(f"{indent}{closer}")
    return text[: m.start()] + "\n".join(lines) + text[m.end() :]


def set_key(text: str, pattern: str, value: str, *, what: str) -> str:
    """Rewrite one `key = value` line, where `pattern` has a single group."""
    pat = re.compile(pattern, re.M)
    if not pat.search(text):
        die(f"{what}: no line matching {pattern!r}; the CLI and the config are out of sync")
    return pat.sub(lambda m: m.group(0).replace(m.group(1), value, 1), text, count=1)


# -- fully generated files ---------------------------------------------------


def render_ghostty_theme(t: Theme) -> str:
    term = t.terminal
    lines = [f"palette = {i}={c}" for i, c in enumerate(term["palette"])]
    return "\n".join(
        lines
        + [
            "",
            f"background = {term['background']}",
            f"foreground = {term['foreground']}",
            "",
            f"cursor-color = {term['cursor']}",
            f"cursor-text = {term['cursor_text']}",
            "",
            f"selection-background = {term['selection_bg']}",
            f"selection-foreground = {term['selection_fg']}",
            "",
        ]
    )


def render_btop_theme(t: Theme) -> str:
    e, d, r = t.editor, t.desktop, t.btop_ramps

    def block(prefix: str, stops: list[str]) -> list[str]:
        names_ = ("start", "mid", "end")
        return [f'theme[{prefix}_{n}]="{c}"' for n, c in zip(names_, stops)]

    out = [
        # main_bg stays empty so the meters sit on ghostty's translucency
        # rather than painting an opaque rectangle over the desktop.
        'theme[main_bg]=""',
        f'theme[main_fg]="{e["fg"]}"',
        f'theme[title]="{d["foreground"]}"',
        f'theme[hi_fg]="{d["accent"]}"',
        f'theme[selected_bg]="{e["bg_sel"]}"',
        f'theme[selected_fg]="{d["foreground"]}"',
        f'theme[inactive_fg]="{e["comment"]}"',
        f'theme[graph_text]="{e["comment"]}"',
        f'theme[meter_bg]="{e["bg_sel"]}"',
        f'theme[proc_misc]="{e["teal"]}"',
        "",
    ]
    out += [f'theme[{box}]="{e["bg_sel"]}"' for box in
            ("cpu_box", "mem_box", "net_box", "proc_box", "div_line")]
    out += [""]
    # The gradient trio is shared with waybar's meters on purpose: the README's
    # rule is that the meter you clicked and the box it opens are one colour.
    out += block("temp", [d["accent"], d["status_alert"], d["status_bad"]]) + [""]
    out += block("cpu", [d["status_good"], d["status_alert"], d["status_bad"]]) + [""]
    out += block("free", r["green"]) + [""]
    out += block("cached", r["accent"]) + [""]
    out += block("available", r["steel"]) + [""]
    out += block("used", r["used"]) + [""]
    out += block("download", r["green"]) + [""]
    out += block("upload", r["accent"]) + [""]
    out += block("process", r["process"])
    return "\n".join(out) + "\n"


def render_nvim_palette(t: Theme) -> str:
    e = t.editor
    groups = (
        ("background",),
        ("bg", "bg_line", "bg_panel", "bg_sel", "bg_float"),
        ("bg_chrome", "bg_tab", "chrome_line"),
        ("fg", "fg_dim", "comment", "gutter"),
        ("pink", "salmon", "sand", "orange", "teal", "mint", "cyan", "steel", "lilac", "purple"),
        ("select_blue", "highlight_yellow"),
        ("diff_add", "diff_delete", "diff_text"),
        ("indent_marker", "backdrop"),
        ("red", "green", "yellow", "blue"),
    )
    out = [f"-- {GENERATED_BY.format(name=t.name)}", "return {"]
    for i, group in enumerate(groups):
        if i:
            out.append("")
        for key in group:
            value = t.meta["background"] if key == "background" else e[key]
            out.append(f'  {key} = "{value}",')
    out += ["}", ""]
    return "\n".join(out)


def render_shell_color(t: Theme) -> str:
    d, w = t.desktop, t.washes
    return f"""pragma Singleton

import QtQuick

// {GENERATED_BY.format(name=t.name)}
//
// One palette for every shell surface. These are the values hyprlock.conf and
// waybar-style.css already use, so a popup summoned over the bar reads as part
// of the same desktop rather than as a separate app.
QtObject {{
  // Surfaces. `background` is the card itself, deliberately not opaque: the
  // layer rule in hyprland.lua blurs whatever sits behind it.
  readonly property color background: "{d['card']}"
  readonly property color elevated: "{d['elevated']}"
  readonly property color scrim: "{d['scrim']}"

  // Hairlines. `border` outlines the card, `separator` divides rows inside it.
  readonly property color border: "{d['border']}"
  readonly property color separator: "{d['separator']}"

  // Text. `muted` is the secondary line under a title; `faint` is for hints
  // that should register only when looked at directly.
  readonly property color foreground: "{d['foreground']}"
  readonly property color muted: "{d['muted']}"
  readonly property color faint: "{d['faint']}"

  readonly property color accent: "{d['accent']}"
  readonly property color selection: "{d['selection']}"

  // Text and glyphs that sit *on* an accent fill. Not always white: on a light
  // accent -- any of the Catppuccin blues -- white reads as a smudge, so this
  // flips to the darkest surface instead.
  readonly property color onAccent: "{d['on_accent']}"

  // Overlay washes, lightest first. Named by weight rather than by use so one
  // value can serve a fill and a hairline alike. They stay alpha rather than
  // becoming opaque surfaces: the cards are blurred by the layer rule in
  // hyprland.lua, and an opaque fill would throw that away.
  readonly property color washFaint: "{w['faint']}"
  readonly property color washDim: "{w['dim']}"
  readonly property color washSoft: "{w['soft']}"
  readonly property color wash: "{w['base']}"
  readonly property color washBorder: "{w['border']}"
  readonly property color washHover: "{w['hover']}"
  readonly property color washStrong: "{w['strong']}"
  readonly property color washBold: "{w['bold']}"

  // State colours. Container state is the only thing in the popup carrying
  // colour, so these have to stay apart at the size of a dot.
  readonly property color green: "{d['status_good']}"
  readonly property color amber: "{d['status_warn']}"
  readonly property color yellow: "{d['status_alert']}"
  readonly property color red: "{d['status_bad']}"
  readonly property color grey: "{d['grey']}"
}}
"""


# Qt's QPalette::ColorRole order, as qt6ct writes it.
QT_ROLES = (
    "WindowText", "Button", "Light", "Midlight", "Dark", "Mid", "Text",
    "BrightText", "ButtonText", "Base", "Window", "Shadow", "Highlight",
    "HighlightedText", "Link", "LinkVisited", "AlternateBase", "NoRole",
    "ToolTipBase", "ToolTipText", "PlaceholderText",
)


def render_qt6ct_colors(t: Theme) -> str:
    """A qt6ct colour scheme: 21 #AARRGGBB roles, in three activity groups."""
    e, d = t.editor, t.desktop

    def argb(colour: str, alpha: str = "ff") -> str:
        h = colour.lstrip("#")
        return f"#{alpha}{h[2:] if len(h) == 8 else h}"

    roles = {
        "WindowText": d["foreground"],
        "Button": e["bg_panel"],
        "Light": e["bg_sel"],
        "Midlight": e["bg_panel"],
        "Dark": e["chrome_line"],
        "Mid": e["bg_chrome"],
        "Text": d["foreground"],
        "BrightText": d["status_bad"],
        "ButtonText": d["foreground"],
        "Base": e["bg"],
        "Window": e["bg_chrome"],
        "Shadow": e["backdrop"],
        "Highlight": d["accent"],
        "HighlightedText": d["on_accent"],
        "Link": d["accent"],
        "LinkVisited": e["purple"],
        "AlternateBase": e["bg_line"],
        "NoRole": e["bg"],
        "ToolTipBase": e["bg_panel"],
        "ToolTipText": d["foreground"],
    }
    active = [argb(roles[r]) for r in QT_ROLES[:-1]]
    active.append(argb(d["muted"], "80"))  # PlaceholderText, half-transparent

    disabled = list(active)
    disabled[QT_ROLES.index("WindowText")] = argb(e["gutter"])
    disabled[QT_ROLES.index("Text")] = argb(e["gutter"])
    disabled[QT_ROLES.index("ButtonText")] = argb(e["gutter"])
    disabled[QT_ROLES.index("HighlightedText")] = argb(e["gutter"])

    return "\n".join(
        [
            f"# {GENERATED_BY.format(name=t.name)}",
            "[ColorScheme]",
            f"active_colors={', '.join(active)}",
            f"disabled_colors={', '.join(disabled)}",
            f"inactive_colors={', '.join(active)}",
            "",
        ]
    )


