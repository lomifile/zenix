def rewrite_fzf(text: str, t: Theme) -> str:
    e = t.editor
    body = "\n".join(
        [
            "# bg:-1 keeps the terminal's own background, so fzf inherits ghostty's",
            "# transparency instead of painting an opaque rectangle over it.",
            f"--color=fg:{e['fg_dim']},bg:-1,hl:{e['cyan']}",
            f"--color=fg+:{e['fg']},bg+:{e['bg_sel']},hl+:{e['cyan']}",
            f"--color=info:{e['comment']},border:{e['bg_panel']},separator:{e['bg_panel']}",
            f"--color=prompt:{e['cyan']},pointer:{e['teal']},marker:{e['orange']}",
            f"--color=spinner:{e['lilac']},header:{e['comment']},label:{e['fg_dim']}",
            f"--color=query:{e['fg']},scrollbar:{e['bg_panel']},gutter:-1",
            f"--color=preview-fg:{e['fg_dim']},preview-bg:-1,preview-border:{e['bg_panel']}",
        ]
    )
    return replace_block(text, "hash", body, what="fzf/fzfrc")


def rewrite_tmux(text: str, t: Theme) -> str:
    e = t.editor
    # Slots are mapped by how tokyo-night-tmux *uses* them, not by ANSI name:
    # `bblack` is a panel background in its format strings, so it takes a dark
    # value rather than the bright grey ANSI would imply.
    slots = (
        ("background", e["bg"]), ("foreground", e["fg"]), (None, None),
        ("black", e["bg_sel"]), ("red", e["salmon"]), ("green", e["teal"]),
        ("yellow", e["sand"]), ("blue", e["steel"]), ("magenta", e["pink"]),
        ("cyan", e["cyan"]), ("white", e["fg"]), (None, None),
        ("bblack", e["bg_panel"]), ("bred", e["orange"]), ("bgreen", e["mint"]),
        ("byellow", e["sand"]), ("bblue", e["cyan"]), ("bmagenta", e["lilac"]),
        ("bcyan", e["mint"]), ("bwhite", e["fg_dim"]), (None, None),
        ("ghgreen", e["teal"]), ("ghmagenta", e["purple"]), ("ghred", e["salmon"]),
        ("ghyellow", e["orange"]),
    )
    lines = ["declare -A THEME=("]
    for key, value in slots:
        lines.append("" if key is None else f'  ["{key}"]="{value}"')
    lines.append(")")
    return replace_block(text, "hash", "\n".join(lines), what="tmux/themes.sh")


