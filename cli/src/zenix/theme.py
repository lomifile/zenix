def set_ghostty_selector(text: str, name: str) -> str:
    return set_key(text, r"^theme = (\S+)", name, what="ghostty/config.ghostty")


def set_btop_selector(text: str, name: str) -> str:
    return set_key(text, r'^color_theme = "([^"]*)"', name, what="btop/btop.conf")


def set_qt6ct_selector(text: str, scheme: str) -> str:
    return set_key(text, r"^color_scheme_path=(.*)$", scheme, what="qt6ct/qt6ct.conf")


def set_fastfetch_label(text: str, label: str) -> str:
    return set_key(text, r'"key": "\S+ theme",\s*"format": "([^"]*)"', label,
                   what="fastfetch/config.jsonc")


# -- the plan ----------------------------------------------------------------


# install.sh's write_qt6ct_conf expands this to $HOME.
HOME_PLACEHOLDER = "__HOME__"


def generates_qt_colors(t: Theme) -> bool:
    return t.apps["qt_scheme"] == "generated"


def qt_scheme_path(t: Theme) -> str:
    """The value for qt6ct.conf's `color_scheme_path=`.

    qt6ct resolves this as an absolute path and does no `~` or `$HOME`
    expansion, so a palette of our own cannot be named in the committed repo
    without baking one machine's username into it. The repo copy therefore
    carries a placeholder and install.sh writes the real path, the same
    arrangement hyprpaper.conf and .zshenv already use.

    An absolute path names one of qt6ct's own stock schemes and is used as-is.
    """
    scheme = t.apps["qt_scheme"]
    if scheme.startswith("/"):
        return scheme
    return f"{HOME_PLACEHOLDER}/.config/qt6ct/colors/{t.name}.conf"


def selectable_files(repo) -> dict[Path, str]:
    """One file per theme, for the apps that select a theme by name.

    All of them are written, not just the active one, so ghostty/themes/,
    btop/themes/ and qt6ct/colors/ are always complete -- install.sh links
    those as directories, and a half-populated one means the selector line can
    name a file that is not there.
    """
    out: dict[Path, str] = {}
    for name in names(repo):
        t = load(repo, name)
        out[repo.root / "ghostty" / "themes" / t.name] = render_ghostty_theme(t)
        out[repo.root / "btop" / "themes" / f"{t.name}.theme"] = render_btop_theme(t)
        if generates_qt_colors(t):
            out[repo.root / "qt6ct" / "colors" / f"{t.name}.conf"] = render_qt6ct_colors(t)
    return out


def generated_files(t: Theme, repo) -> dict[Path, str]:
    """The files that hold only the *active* theme, written outright."""
    return {
        repo.root / "nvim" / "lua" / "zenix" / "palette.lua": render_nvim_palette(t),
        repo.root / "shell" / "Commons" / "Color.qml": render_shell_color(t),
    }


# (path, rewriter) for every file whose text is preserved around the change.
REWRITES = (
    (("fzf", "fzfrc"), rewrite_fzf),
    (("tmux", "themes.sh"), rewrite_tmux),
    (("waybar", "waybar-style.css"), rewrite_waybar_css),
    (("waybar", "waybar-config.jsonc"), rewrite_waybar_config),
    (("waybar", "scripts", "agenda.py"), rewrite_agenda_script),
    (("wofi", "style.css"), rewrite_wofi_css),
    (("hypr", "hyprland.lua"), rewrite_hyprland_lua),
    (("hypr", "hyprlock.conf"), rewrite_hyprlock),
    (("sddm", "zenix", "theme.conf"), rewrite_sddm_theme_conf),
    (("lazygit", "config.yml"), rewrite_lazygit),
    (("grub", "theme", "theme.txt"), rewrite_grub_theme),
)


def rewritten_files(t: Theme, repo) -> dict[Path, str]:
    """Every file rewritten in place, as {path: new text}.

    A file that is missing is skipped rather than fatal: grub/ and sddm/ are
    optional parts of the setup, and a checkout can legitimately lack them.
    """
    out: dict[Path, str] = {}
    for parts, fn in REWRITES:
        path = repo.root.joinpath(*parts)
        if not path.is_file():
            continue
        out[path] = fn(path.read_text(), t)

    selectors = (
        (("ghostty", "config.ghostty"), lambda s: set_ghostty_selector(s, t.name)),
        (("btop", "btop.conf"), lambda s: set_btop_selector(s, t.name)),
        (("qt6ct", "qt6ct.conf"), lambda s: set_qt6ct_selector(s, qt_scheme_path(t))),
        (("fastfetch", "config.jsonc"), lambda s: set_fastfetch_label(s, t.label)),
    )
    for parts, fn in selectors:
        path = repo.root.joinpath(*parts)
        if not path.is_file():
            continue
        out[path] = fn(out.get(path, path.read_text()))
    return out


def plan(t: Theme, repo) -> dict[Path, str]:
    """Everything `zenix theme set` would write, as {path: text}."""
    files = selectable_files(repo)
    files.update(generated_files(t, repo))
    files.update(rewritten_files(t, repo))
    return files
