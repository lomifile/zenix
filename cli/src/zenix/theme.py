def rewrite_lazygit(text: str, t: Theme) -> str:
    """Replace the `gui.theme:` mapping, leaving the other ~180 lines alone.

    Anchored on the YAML structure rather than on marker comments: lazygit
    rewrites this whole file whenever a setting is toggled in the app, and it
    does not preserve comments.
    """
    e = t.editor
    lines = ["  theme:"]
    for key, role, attr in LAZYGIT_THEME_KEYS:
        if key == "selectedLineBgColor":
            lines.append(
                "    # The palette's own selection colour: a quiet fill, not a"
                " saturated bar."
            )
        lines.append(f"    {key}:")
        lines.append(f"      - '{e[role]}'")
        if attr:
            lines.append(f"      - {attr}")

    pat = re.compile(r"^  theme:\n(?:(?:    |      )[^\n]*\n|\n)*", re.M)
    m = pat.search(text)
    if not m:
        die("lazygit/config.yml has no `  theme:` block; the CLI and the config are out of sync")
    return text[: m.start()] + "\n".join(lines) + "\n" + text[m.end():]


