def rewrite_hyprland_lua(text: str, t: Theme) -> str:
    h = t.hypr
    body = "\n".join(
        [
            "local c = {",
            f'\tborder_active_1 = "{h["border_active_1"]}",',
            f'\tborder_active_2 = "{h["border_active_2"]}",',
            f'\tborder_inactive = "{h["border_inactive"]}",',
            f'\tgroup_active = "{h["group_border_active"]}",',
            f'\tgroup_inactive = "{h["group_border_inactive"]}",',
            f"\tshadow = {h['shadow']},",
            "}",
        ]
    )
    text = replace_block(text, "lua", body, what="hypr/hyprland.lua")

    apps = t.apps
    text = set_key(text, r'hl\.env\("GTK_THEME", "([^"]*)"\)', apps["gtk_env"],
                   what="hypr/hyprland.lua")
    text = set_key(text, r'gsettings set org\.gnome\.desktop\.interface gtk-theme ([^"]*)"',
                   apps["gtk_theme"], what="hypr/hyprland.lua")
    text = set_key(text, r'gsettings set org\.gnome\.desktop\.interface icon-theme ([^"]*)"',
                   apps["icon_theme"], what="hypr/hyprland.lua")
    text = set_key(text,
                   r'gsettings set org\.gnome\.desktop\.interface color-scheme ([^"]*)"',
                   "prefer-dark" if t.is_dark else "prefer-light",
                   what="hypr/hyprland.lua")
    return text


# (block, key) -> theme role. `color` means different things in different
# blocks, and there are two `label` blocks, so the block has to be tracked
# rather than matched on the key alone.
HYPRLOCK_KEYS = {
    ("background", "color"): "bg",
    ("input-field", "outer_color"): "outer",
    ("input-field", "inner_color"): "inner",
    ("input-field", "font_color"): "font",
    ("label:1", "color"): "clock",
    ("label:2", "color"): "date",
}


def rewrite_hyprlock(text: str, t: Theme) -> str:
    """Rewrite the colour values in place, block by block.

    Deliberately not done with hyprlang `$variable` declarations. They would be
    tidier, but `placeholder_text` carries Pango markup whose `#` is doubled to
    survive hyprlang's comment parsing, and whether a variable expands inside
    that quoted attribute is not something that can be checked without locking
    the screen to find out. Replacing the literals needs no new syntax.

    `path =` in the background block is left alone: it is owned by `zenix
    wallpaper` and by install.sh, which both sed it to the resolved image.
    """
    lk = t.hyprlock
    block = None
    seen: dict[str, int] = {}
    out: list[str] = []
    changed = 0

    for line in text.splitlines():
        if m := re.match(r"^(\S+)\s*\{", line):
            block = m.group(1)
            seen[block] = seen.get(block, 0) + 1
            if block == "label":
                block = f"label:{seen[block]}"
        elif line.strip() == "}":
            block = None
        elif block:
            if m := re.match(r"^(\s*)(\w+)\s*=\s*(.*)$", line):
                role = HYPRLOCK_KEYS.get((block, m.group(2)))
                if role:
                    line = f"{m.group(1)}{m.group(2)} = {lk[role]}"
                    changed += 1
                elif m.group(2) == "placeholder_text":
                    line = re.sub(r'foreground="[^"]*"',
                                  f'foreground="{lk["placeholder"]}"', line)
                    changed += 1
        out.append(line)

    if changed != len(HYPRLOCK_KEYS) + 1:
        die(
            f"hypr/hyprlock.conf: changed {changed} colours, expected "
            f"{len(HYPRLOCK_KEYS) + 1}; the CLI and the config are out of sync"
        )
    return "\n".join(out) + ("\n" if text.endswith("\n") else "")


# SDDM reads theme.conf through Qt's own config object, which has no notion of
# a ladder, so the rungs it needs are spelled out as flat keys.
SDDM_WASHES = (
    ("washSoft", "soft"), ("wash", "base"), ("washBorder", "border"),
    ("washHover", "hover"), ("washStrong", "strong"),
)


def rewrite_sddm_theme_conf(text: str, t: Theme) -> str:
    pairs = [(k, v) for k, v in t.sddm.items() if not k.startswith("_")]
    pairs += [(key, t.washes[rung]) for key, rung in SDDM_WASHES]
    body = "\n".join(f"{k}={v}" for k, v in pairs)
    return replace_block(text, "hash", body, what="sddm/zenix/theme.conf")


def rewrite_grub_theme(text: str, t: Theme) -> str:
    g = t.grub
    text = set_key(text, r'^desktop-color: "([^"]*)"', g["desktop"], what="grub/theme/theme.txt")
    text = set_key(text, r'^message-color: "([^"]*)"', g["message"], what="grub/theme/theme.txt")
    text = set_key(text, r'^message-bg-color: "([^"]*)"', g["desktop"],
                   what="grub/theme/theme.txt")
    text = set_key(text, r'item_color\s+= "([^"]*)"', g["item"], what="grub/theme/theme.txt")
    text = set_key(text, r'selected_item_color = "([^"]*)"', g["item_selected"],
                   what="grub/theme/theme.txt")
    text = set_key(text, r'bg_color\s+= "([^"]*)"', g["bar_bg"], what="grub/theme/theme.txt")
    text = set_key(text, r'fg_color\s+= "([^"]*)"', g["bar_fg"], what="grub/theme/theme.txt")
    text = set_key(text, r'border_color = "([^"]*)"', g["bar_bg"], what="grub/theme/theme.txt")
    return text


def rewrite_agenda_script(text: str, t: Theme) -> str:
    w = t.waybar
    body = "\n".join([f'DIM = "{w["agenda_dim"]}"', f'ALERT = "{w["agenda_alert"]}"'])
    return replace_block(text, "hash", body, what="waybar/scripts/agenda.py")


def rewrite_waybar_config(text: str, t: Theme) -> str:
    """The clock's calendar carries Pango markup, so its colours are inline."""
    w = t.waybar
    for key, role in (
        ("months", "cal_fg"),
        ("days", "cal_fg"),
        ("weeks", "cal_dim"),
        ("weekdays", "cal_dim"),
        ("today", "cal_today"),
    ):
        text = set_key(text, rf'"{key}":\s*"<span color=\'([^\']*)\'>', w[role],
                       what="waybar/waybar-config.jsonc")
    return text


